# Ejemplo: Variables y Tipos de Datos

# 1. Cadenas de texto (Strings)
nombre = "Aprendiz de Python"
lenguaje = 'Python'
mensaje = f"Hola, {nombre}. Estás aprendiendo {lenguaje}."
print(mensaje)

# 2. Números (Integers y Floats)
edad = 25
precio = 19.99
cantidad = 3
total = precio * cantidad
print(f"Total de la compra: ${total}")

# 3. Booleanos (True / False)
es_programador = True
le_gusta_el_cafe = False

# 4. Verificando tipos
print(f"El tipo de 'edad' es: {type(edad)}")
print(f"El tipo de 'precio' es: {type(precio)}")
